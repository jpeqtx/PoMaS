## 5.8 メモリ M

### メモリの概要

**メモリ M** は、変数とは別の単一記憶領域です。
古典的な電卓の「M+」「M-」「MR」に相当します。

### メモリ操作（Fn + 3）

```
┌─────────────────────────────────┐
│▌Memory M=0                      │
├─────────────────────────────────┤
│1 M+ (M += Ans)                  │
│2 M- (M -= Ans)                  │
│3 MR (Ans <- M)                  │
│4 MC (M = 0)                     │
│5 Set M = ...                    │
│6 Back                           │
└─────────────────────────────────┘
```

| 操作 | 動作 |
|---|---|
| M+ | M に Ans を加算 |
| M- | M から Ans を減算 |
| MR | Ans に M をコピー |
| MC | M を 0 にクリア |
| Set | M に直接値を設定 |

### 使用例

**例: 合計を計算**

```
[1] 10 Enter → Ans = 10
[2] Fn+3 → M+ (M = 10)
[3] 20 Enter → Ans = 20
[4] Fn+3 → M+ (M = 30)
[5] 15 Enter → Ans = 15
[6] Fn+3 → M+ (M = 45)
[7] Fn+3 → MR (Ans = 45)
```

合計 45 が Ans にセットされます。

