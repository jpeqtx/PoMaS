## 5.6 変数 A〜J

### 変数とは

**変数** は、数値に名前を付けて保存する仕組みです。
計算の途中経過や、よく使う値を覚えておけます。

PoMaS では、**A〜J の 10 個** の変数が使えます。
大文字・小文字の両方で参照できます。

### 変数の使い方

**Step 1: 変数に値を代入**

`Fn + 4` で変数メニューを開きます。

```
┌─────────────────────────────────┐
│▌Variables A..J                  │
├─────────────────────────────────┤
│1 A = 0                          │
│2 B = 0                          │
│3 C = 0                          │
│4 D = 0                          │
│5 E = 42                         │
│...                              │
└─────────────────────────────────┘
```

`5`（E）を選ぶと、値を入力できます。
`42` と入力して Enter。

**Step 2: 変数を式で使う**

Calculator 画面で:

```
E * 2 Enter → 84
```

### 変数の参照

| 入力 | 参照される値 |
|---|---|
| `A` | 変数 A の値 |
| `a` | 変数 A の値（小文字も同じ） |
| `E` | 変数 E の値 |
| `e` | オイラー数（定数、変数 E ではない） |

⚠️ **E と e の違い**
- `E`（大文字）: 変数 E（デフォルト 0、ユーザーが変更可能）
- `e`（小文字）: オイラー数 2.718...

混同しやすいので注意。

### 変数の使用例

**例: 三角形の面積を計算**

```
[1] Fn+4 → A に底辺 6 を代入
[2] Fn+4 → B に高さ 4 を代入
[3] A * B / 2 Enter → 12
```

**例: 連立方程式**

```
[1] A = 2, B = 3, C = 8
[2] A * 2 + B Enter → 7
[3] A * 3 + B * 2 Enter → 12
```

