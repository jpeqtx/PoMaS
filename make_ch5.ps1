## 5.5 定数

### 数学定数

| 名前 | 値 | 入力 |
|---|---|---|
| 円周率 π | 3.14159... | `pi` |
| ネイピア数 e | 2.71828... | `e` または `euler` |
| 黄金比 φ | 1.61803... | `phi` |
| オイラー・マスケローニ | 0.57721... | `gamma` |
| 無限大 | ∞ | `inf` |
| 非数 | NaN | `nan` |

### 直前の結果（Ans）

```
10 * 2 Enter → 20
Ans + 5 Enter → 25
Ans * 2 Enter → 50
```

`Ans` は直前の計算結果を参照します。
連続した計算で便利です。

### メモリ（mem）

`mem` は独立したメモリ領域です。
`Fn + 3` から操作できます。

```
mem = 100  (Fn + 3 で設定)
mem * 2 Enter → 200
```

