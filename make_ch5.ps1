## 5.9 Ans バンク

### Ans バンクとは

**Ans バンク** は、複数の Ans を保存できる機能です。
最大 **20 件** まで保存できます。

古典的な電卓にはない、PoMaS 独自の機能です。

### 使い方（Fn + b）

```
┌─────────────────────────────────┐
│▌Ans Bank (3/20)                 │
├─────────────────────────────────┤
│1 Ans      = 5                   │
│2 Ans      = 20                  │
│3 Ans      = 45                  │
│4 [+] Add current Ans            │
│5 [V] Pop to variable A..J       │
│6 [C] Clear all bank             │
│7 [<-] Back                      │
└─────────────────────────────────┘
```

### 主な操作

| 操作 | 意味 |
|---|---|
| エントリ選択 | Insert / Ans に戻す / 変数へ / 削除 |
| [+] Add | 現在の Ans をバンクに追加 |
| [V] Pop | 最後のエントリを変数に移送 |
| [C] Clear | バンク全体をクリア |

### 使用例

**例: 3 つの異なる計算結果を保存**

```
[1] 5 Enter
[2] Fn+b → [+] Add (エントリ1 = 5)
[3] 20 Enter
[4] Fn+b → [+] Add (エントリ2 = 20)
[5] 45 Enter
[6] Fn+b → [+] Add (エントリ3 = 45)

後で:
[7] Fn+b → エントリ1を選択
[8] "Insert into expression" を選ぶ
[9] 入力欄に 5 が挿入される
```

💡 **統計計算の途中結果を保持**
平均・分散・標準偏差を別々に計算して Ans バンクに保存し、
最後に組み合わせて使う、といった使い方ができます。

