## 5.1 Calculator モードの画面

Calculator モードは、PoMaS の中心となる機能です。
日常の計算から高度な関数計算まで、あらゆる計算をここで行います。

### 画面レイアウト

```
┌─────────────────────────────────┐
│▌Calculator          DEG|NRM     │  ← ヘッダ
├─────────────────────────────────┤
│2+3 = 5                          │
│10*2 = 20                        │  ← 履歴（過去 3 件）
│sin(30) = 0.5                    │
│                                 │
│                                 │
│Ans = 20                         │  ← 直前の結果
│─────────────────────────────────│
│_                                │  ← 入力欄
├─────────────────────────────────┤
│Fn+0:Help            Fn+9:RPN    │  ← フッタ
└─────────────────────────────────┘
```

### 各領域の役割

| 領域 | 内容 |
|---|---|
| **履歴** | 過去 3 回の計算結果（式と答え） |
| **Ans** | 直前の計算結果 |
| **入力欄** | 現在入力中の式 |
| **ヘッダバッジ** | 角度モード（DEG/RAD/GRA）と表示形式（NRM/FIX/SCI/ENG） |

