## 5.2 四則演算

### 足し算

**例: 2 + 3 を計算する**

```
[1] 2 を押す
[2] + を押す
[3] 3 を押す
[4] Enter を押す

結果: Ans = 5
```

### 引き算

**例: 10 - 4**

```
10 - 4 Enter → 6
```

💡 **負の数**
`-5 + 3` のように、先頭に `-` を付けられます。
`2 + -3` も `2 - 3` と同じ結果です。

### 掛け算

**例: 6 × 7**

```
6 * 7 Enter → 42
```

⚠️ **`×` 記号は使わない**
`*`（アスタリスク）を使います。

### 割り算

**例: 20 ÷ 4**

```
20 / 4 Enter → 5
```

⚠️ **ゼロで割ると**
`10 / 0` → `ERR: division by zero`（エラー）

### 複合演算

**例: (2 + 3) × 4**

```
(2+3)*4 Enter → 20
```

**演算子の優先順位**:

| 優先度 | 演算子 |
|---|---|
| 高 | `()`（括弧） |
| ↓ | `^`（べき乗） |
| ↓ | `!`（階乗） |
| ↓ | `*`, `/`, `%`（乗除算） |
| 低 | `+`, `-`（加減算） |

💡 **迷ったら括弧を付ける**
`2+3*4` は `2+(3*4) = 14` になります。
`(2+3)*4 = 20` としたい場合は括弧が必須です。

