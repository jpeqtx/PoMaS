## 5.3 べき乗と階乗

### べき乗

**例: 2 の 10 乗**

```
2^10 Enter → 1024
```

**負の指数**

```
2^-3 Enter → 0.125
```

**小数の指数**

```
9^0.5 Enter → 3  （√9 と同じ）
```

### 階乗（!）

**例: 5 の階乗（5! = 5×4×3×2×1）**

```
5! Enter → 120
```

**大きな階乗**

```
10! Enter → 3628800
20! Enter → 2.43e18
```

💡 **階乗の上限**
内部的には 170! 程度まで計算できますが、
それ以上は無限大（Inf）になります。

