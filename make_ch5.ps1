## 5.4 数学関数

### 三角関数

**角度モードに注意**
三角関数の結果は、現在の角度モード（DEG/RAD/GRA）に依存します。

| モード | 30 の意味 |
|---|---|
| DEG | 30° |
| RAD | 30 ラジアン（約 1718°） |
| GRA | 30 グラジアン（= 27°） |

**デフォルトは DEG**（度数法）です。

**例: sin(30°)**

```
sin(30) Enter → 0.5
```

**例: cos(60°)**

```
cos(60) Enter → 0.5
```

**例: tan(45°)**

```
tan(45) Enter → 1
```

### 逆三角関数

**例: arcsin(0.5) を DEG で求める**

```
asin(0.5) Enter → 30
```

結果は **30**（30°）です。角度モードに応じた単位で返ります。

### 双曲線関数

**例: sinh(1)**

```
sinh(1) Enter → 1.1752
```

| 関数 | 意味 |
|---|---|
| `sinh` | 双曲線正弦 |
| `cosh` | 双曲線余弦 |
| `tanh` | 双曲線正接 |
| `asinh` | 逆双曲線正弦 |
| `acosh` | 逆双曲線余弦 |
| `atanh` | 逆双曲線正接 |

### 指数・対数

| 関数 | 意味 | 例 |
|---|---|---|
| `exp(x)` | e の x 乗 | `exp(1) = 2.718` |
| `ln(x)` | 自然対数 | `ln(e) = 1` |
| `log(x)` | 常用対数（底 10） | `log(100) = 2` |
| `log2(x)` | 底 2 の対数 | `log2(8) = 3` |
| `logn(a,b)` | 底 a の b の対数 | `logn(3,81) = 4` |

⚠️ **`log` は底 10**
`ln` と間違えないように注意。
底 10 の対数は `log`、自然対数は `ln` です。

### 平方根・立方根

| 関数 | 意味 | 例 |
|---|---|---|
| `sqrt(x)` | 平方根 | `sqrt(16) = 4` |
| `cbrt(x)` | 立方根 | `cbrt(27) = 3` |
| `nrt(n,x)` | n 乗根 | `nrt(3,27) = 3` |

### 絶対値・符号

| 関数 | 意味 | 例 |
|---|---|---|
| `abs(x)` | 絶対値 | `abs(-5) = 5` |
| `sign(x)` | 符号 | `sign(-3) = -1` |
| `sgn(x)` | 符号（同上） | `sgn(0) = 0` |

### 丸め

| 関数 | 意味 | 例 |
|---|---|---|
| `floor(x)` | 切り捨て | `floor(3.7) = 3` |
| `ceil(x)` | 切り上げ | `ceil(3.2) = 4` |
| `round(x)` | 四捨五入 | `round(3.5) = 4` |
| `int(x)` | 整数部 | `int(3.7) = 3` |
| `frac(x)` | 小数部 | `frac(3.7) = 0.7` |

### 組合せ・順列

| 関数 | 意味 | 例 |
|---|---|---|
| `nCr(n,r)` | 組合せ（n から r 選ぶ） | `nCr(5,2) = 10` |
| `nPr(n,r)` | 順列（順番も区別） | `nPr(5,2) = 20` |

**使い分け**:
- **組合せ（nCr）**: 順番を区別しない。「5 人から 2 人の委員を選ぶ」
- **順列（nPr）**: 順番を区別する。「5 人から 1 位と 2 位を選ぶ」

### その他

| 関数 | 意味 |
|---|---|
| `gcd(a,b)` | 最大公約数 |
| `lcm(a,b)` | 最小公倍数 |
| `isPrime(n)` | 素数判定（1 or 0） |
| `nextPrime(n)` | 次の素数 |
| `prevPrime(n)` | 前の素数 |
| `hypot(x,y)` | √(x² + y²) |
| `min(a,b)` | 最小値 |
| `max(a,b)` | 最大値 |
| `mod(a,b)` | a を b で割った余り |
| `pow(a,b)` | a の b 乗（`^` と同じ） |
| `random()` | 0〜1 の乱数 |
| `randInt(n)` | 0〜n-1 のランダム整数 |
| `randN(sd)` | 平均 0、標準偏差 sd の正規乱数 |
| `randR(a,b)` | a〜b の乱数 |

