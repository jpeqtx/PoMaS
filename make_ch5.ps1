## 5.11 角度モード

### 3 つの角度モード

| モード | 単位 | 1 周 |
|---|---|---|
| **DEG** | 度数法 | 360° |
| **RAD** | 弧度法 | 2π（約 6.28） |
| **GRA** | グラジアン | 400 |

### 切り替え

`Settings → Angle` または `Fn + 1`。

### 三角関数への影響

同じ `sin(30)` でも、モードによって結果が変わります。

| モード | sin(30) |
|---|---|
| DEG | 0.5（30°） |
| RAD | -0.988（30 rad） |
| GRA | 0.454（30 grad） |

⚠️ **モードの確認**
三角関数を使う前に、ヘッダのバッジで現在のモードを確認してください。

