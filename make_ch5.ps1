## 5.7 履歴

### 履歴の概要

PoMaS は、過去 **100 件** の計算を記録しています。
直近 3 件は常に画面に表示されます。

### 履歴の表示

```
┌─────────────────────────────────┐
│2+3 = 5                          │  ← 3 回前
│10*2 = 20                        │  ← 2 回前
│sin(30) = 0.5                    │  ← 直前
│                                 │
```

### 履歴呼び出し（Fn + 2）

過去の計算を呼び出して再実行できます。

```
[1] Fn + 2 で履歴一覧を開く
[2] ; . で移動
[3] Enter で選択

→ 選択した式が入力欄に挿入されます
```

💡 **履歴の再利用**
「あの計算をもう一度」というときに便利です。
値だけを再利用したい場合は、履歴から Ans に転送してから使います。

