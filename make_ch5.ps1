## 5.10 表示形式

### 表示形式の種類

| 形式 | 例 | 説明 |
|---|---|---|
| **Norm** | 1.23456 | 通常の表示 |
| **Fix** | 1.23 | 固定小数点（桁数指定） |
| **Sci** | 1.23e+00 | 科学表記 |
| **Eng** | 1.23 | 工学表記（3 桁区切り） |

### 切り替え

`Settings → Display` または `Fn + 1` で切り替えます。

### 表示桁数

`Fn + ,` で 1 桁増、`Fn + /` で 1 桁減。
0〜9 の範囲で設定できます。

💡 **桁数の目安**
- 3 桁: 概算で十分
- 5 桁: 通常の計算
- 7 桁: 精度重視
- 9 桁: 最大精度

### Norm 1 / Norm 2 の違い

**Norm** は「通常表示」ですが、非常に小さい数や大きい数をどう表示するかで 2 種類あります。

| モード | 小さい数の閾値 | 例 |
|---|---|---|
| Norm 1 | 0.01 未満で指数表示 | `0.005` → `5e-3` |
| Norm 2 | 0.000000001 未満で指数表示 | `0.005` → `0.005` |

💡 **迷ったら Norm 1**
Norm 1 は「0.01 未満は指数表示」なので、科学技術計算向き。
Norm 2 は「日常的な数値を見やすく」したい場合向け。

