## 6.3 基数変換

### 基数とは

普段使う「10 進数」は、10 種類の数字（0〜9）を使います。
これが基数 10 です。

**他の基数**:
- **2 進数**: 0 と 1 のみ
- **8 進数**: 0〜7
- **16 進数**: 0〜9 と A〜F

### 基数変換メニュー（Fn + 5）

```
┌─────────────────────────────────┐
│▌Base Convert                    │
├─────────────────────────────────┤
│ Number:                          │
│  [255                ]           │
└─────────────────────────────────┘

→ 変換結果:
DEC: 255
HEX: 0xFF
OCT: 0o377
BIN: 0b11111111
```

### 例: 10 進数 255 を変換

```
[1] Fn + 5
[2] Number: 255 と入力
[3] Enter

結果:
DEC: 255
HEX: 0xFF
OCT: 0o377
BIN: 0b11111111
```

### 例: 16 進数 0xFF を変換

```
[1] Fn + 5
[2] Number: 0xFF と入力
[3] Enter

結果:
DEC: 255
HEX: 0xFF
OCT: 0o377
BIN: 0b11111111
```

### 入力形式の接頭辞

| 接頭辞 | 基数 | 例 |
|---|---|---|
| （なし） | 10 | `255` |
| `0x` | 16 | `0xFF` |
| `0b` | 2 | `0b1010` |
| `0o` | 8 | `0o777` |

💡 **Y キーで Ans へ**
変換結果を `Ans` に転送して、続けて計算できます。

