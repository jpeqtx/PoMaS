## 6.6 拡張ツール（方程式）

### 拡張ツールメニュー（Fn + 8）

```
┌─────────────────────────────────┐
│▌Tools                           │
├─────────────────────────────────┤
│1 Equation Solver                │
│2 Numerical Analysis             │
│3 Vector / Matrix                │
│4 Geometry (27 shapes)           │
│5 Probability Sim                │
│6 Prime Factorize                │
│7 Back                           │
└─────────────────────────────────┘
```

### 方程式ソルバー

```
┌─────────────────────────────────┐
│▌Equation Solver                 │
├─────────────────────────────────┤
│1 Newton-Raphson f(x)=0          │
│2 Bisection f(x)=0               │
│3 Quadratic ax^2+bx+c            │
│4 Cubic ax^3+...                 │
│5 Quartic ax^4+...               │
│6 Linear System (n<=5)           │
│7 General Polynomial             │
│8 Back                           │
└─────────────────────────────────┘
```

### Newton-Raphson（ニュートン法）

**例: x² - 2 = 0 の根を求める**

```
[1] f(x): x^2 - 2
[2] x0: 1
[3] Enter
→ 根 ≈ 1.41421356（√2）
```

ニュートン法は、初期値 x0 から出発して
接線を引くことで根に近づく反復法です。

### Bisection（二分法）

**例: x² - 2 = 0 の根**

```
[1] f(x): x^2 - 2
[2] a: 0
[3] b: 2
[4] Enter
→ 根 ≈ 1.41421356
```

二分法は、区間 [a,b] で符号が変わる点を
区間を半分に絞りながら探す方法です。

### Quadratic（2 次方程式）

**例: x² - 5x + 6 = 0 の根**

```
a: 1
b: -5
c: 6
→ x1 = 3, x2 = 2
```

### Cubic / Quartic

3 次・4 次方程式の根を求めます。
実数根と複素数根の両方を表示します。

### Linear System（連立 1 次方程式）

**例:**
```
2x + 3y = 8
4x - y = 2
```

```
[1] Size: 2
[2] A[1][1]: 2, A[1][2]: 3, b[1]: 8
[3] A[2][1]: 4, A[2][2]: -1, b[2]: 2
[4] Enter
→ x = 1, y = 2
```

### General Polynomial

**例: x³ - 6x² + 11x - 6 = 0**

```
[1] Degree: 3
[2] x^3: 1
[3] x^2: -6
[4] x^1: 11
[5] x^0: -6
→ r1 = 3, r2 = 2, r3 = 1
```

