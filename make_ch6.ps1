## 6.4 ビット演算

### ビット演算とは

**ビット** は、情報の最小単位（0 か 1）です。
ビット演算は、0 と 1 のレベルで計算する操作です。

プログラムの世界では、フラグ管理や高速計算に使われます。

### ビット演算メニュー（Fn + 6）

```
┌─────────────────────────────────┐
│▌Bit Op                          │
├─────────────────────────────────┤
│1 AND                            │
│2 OR                             │
│3 XOR                            │
│4 NOT                            │
│5 SHL (左シフト)                 │
│6 SHR (右シフト)                 │
│7 Back                           │
└─────────────────────────────────┘
```

### AND（論理積）

**両方 1 のときだけ 1**。

```
  1010
& 1100
─────
  1000
```

**例**: `12 AND 10`

```
12 = 1100
10 = 1010
─────
 8 = 1000

→ 8
```

### OR（論理和）

**どちらか 1 なら 1**。

```
  1010
| 1100
─────
  1110
```

**例**: `12 OR 10 = 14`

### XOR（排他的論理和）

**両方が異なるときだけ 1**。

```
  1010
^ 1100
─────
  0110
```

**例**: `12 XOR 10 = 6`

### NOT（否定）

**すべてのビットを反転**。

```
NOT 1010 = 0101
```

⚠️ **符号付き整数**
NOT は符号を含めて反転するため、
`NOT 5 = -6` になります（2 の補数表現）。

### SHL（左シフト）

**ビットを左にずらす**。n ビット左シフト = 2^n 倍。

```
5 << 1 = 10   (2 倍)
5 << 2 = 20   (4 倍)
```

### SHR（右シフト）

**ビットを右にずらす**。n ビット右シフト = 1/2^n 倍。

```
20 >> 1 = 10   (半分)
20 >> 2 = 5    (1/4)
```

### 使用例

**例: フラグの合成**

```
F1 = 0x01, F2 = 0x02, F3 = 0x04 を全て立てる:
0x01 OR 0x02 OR 0x04 = 0x07
```

**例: 特定ビットの取得**

```
状態値が 0x0A の 1 ビット目:
0x0A AND 0x02 = 0x02  (立っている)
0x0A AND 0x01 = 0x00  (立っていない)
```

