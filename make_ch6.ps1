### 例: コイン投げ 1000 回

```
[1] trials: 1000
[2] Enter
→ Heads: 498, Tails: 502
→ 比率: 0.498
```

理論値 0.5 に近い値が得られます。

### 例: 誕生日パラドックス

「23 人のグループに同じ誕生日の人がいる確率」を計算。

```
[1] # people: 23
[2] trials: 10000
[3] Enter
→ Sim Prob = 0.507
→ Theory   = 0.507
```

23 人いれば 50% 以上の確率で同じ誕生日の人がいる、という有名な話の検証です。

