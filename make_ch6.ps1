## 6.5 RPN モード

### RPN とは

**RPN（Reverse Polish Notation、逆ポーランド記法）** は、
演算子を数の**後**に書く記法です。

| 記法 | 式 |
|---|---|
| 通常（中置） | `2 + 3` |
| RPN（後置） | `2 3 +` |

RPN は、HP の電卓で伝統的に使われてきた方式です。
括弧が不要になるという特徴があります。

### RPN モードへの切り替え

`Fn + 9` を押すと、RPN モードと Algebraic モードが切り替わります。

ヘッダのバッジに `RPN` が表示されれば RPN モードです。

### RPN の動作

**スタック** と呼ばれる仕組みを使います。

```
[1] 2 を入力 → スタック: [2]
[2] 3 を入力 → スタック: [2, 3]
[3] + を入力 → スタック: [5]  (2+3 を計算)
```

### 例: (2+3) × 4

**Algebraic モード**
```
(2+3)*4 Enter → 20
```

**RPN モード**
```
2 Enter → スタック: [2]
3 Enter → スタック: [2, 3]
+ Enter → スタック: [5]
4 Enter → スタック: [5, 4]
* Enter → スタック: [20]
```

### RPN コマンド

| コマンド | 意味 |
|---|---|
| `+ - * /` | 四則演算（スタック上位 2 つ） |
| `^` | べき乗 |
| `neg` | 符号反転 |
| `sqrt` | 平方根 |
| `sin cos tan` | 三角関数 |
| `ln log exp` | 対数・指数 |
| `inv` | 逆数 |
| `swap` | スタック上位 2 つを交換 |
| `dup` | スタック最上位を複製 |
| `drop` | スタック最上位を捨てる |
| `clr` | スタックをクリア |

### RPN の利点と欠点

| 利点 | 欠点 |
|---|---|
| 括弧が不要 | 慣れるまで戸惑う |
| 計算の順序が明示的 | 電卓初心者には難しい |
| スタックで途中結果を保持 | スタックの概念理解が必要 |

💡 **どちらを使うべきか**
普段は Algebraic モード（通常の書き方）がおすすめ。
RPN は「HP 電卓に慣れている方」「複雑な式を括弧なしで書きたい方」向け。

