## 6.11 拡張ツール（素因数分解）

### Prime Factorize

**例: 360 の素因数分解**

```
Number: 360
→ 360 = 2^3 x 3^2 x 5
```

**計算内容**:
360 = 8 × 9 × 5 = 2³ × 3² × 5

### 例: 大きな数の素因数分解

```
Number: 1234567
→ 1234567 = 127 x 9721
```

💡 **素因数分解の用途**
- 暗号理論の学習
- 数の性質の理解
- 約数の計算（すべての素因数から導出可能）

