### ベクトルの編集

**例: ベクトル A = (1, 2, 3) を設定**

```
[1] Dim: 3
[2] A[1]: 1
[3] A[2]: 2
[4] A[3]: 3
```

### ベクトル演算

| 演算 | 意味 |
|---|---|
| A . B | 内積（ドット積） |
| A x B | 外積（クロス積、3D のみ） |
| \|A\| | A のノルム（長さ） |
| A + B | 加算 |
| A - B | 減算 |

**例: A = (1,2,3), B = (4,5,6) の内積**

```
A . B = 1*4 + 2*5 + 3*6 = 32
```

### 行列の編集

**例: 3×3 行列 A を設定**

```
[1] Rows: 3
[2] Cols: 3
[3] A[1][1]: 1
[4] A[1][2]: 2
... （9 個の要素を入力）
```

### 行列演算

| 演算 | 意味 |
|---|---|
| A * B | 行列積 |
| A + B | 加算 |
| A - B | 減算 |
| Transpose A | 転置行列 Aᵀ |
| det A | 行列式 |
| inv A | 逆行列 |
| rank A | 階数 |
| Eigenvalues A | 固有値 |

**例: 2×2 行列 A = [[1,2],[3,4]] の行列式**

```
det A = 1*4 - 2*3 = 4 - 6 = -2
```

**例: 行列 A の固有値**

```
A = [[2,0],[0,3]]
→ λ1 = 3, λ2 = 2
```

⚠️ **固有値は高度**
固有値の計算は大学レベルの線形代数です。
PoMaS では数値的に近似します。

