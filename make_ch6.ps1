## 6.7 拡張ツール（数値解析）

### Numerical Analysis メニュー

```
┌─────────────────────────────────┐
│▌Numerical Analysis              │
├─────────────────────────────────┤
│1 d/dx f(x) at a                 │
│2 Integral f(x) [a,b]            │
│3 Sum f(i) [a,b]                 │
│4 Product f(i) [a,b]             │
│5 Back                           │
└─────────────────────────────────┘
```

### 微分（d/dx）

**例: f(x) = x² の x=3 での微分**

```
[1] f(x): x^2
[2] at x: 3
[3] Enter
→ 6.000000（理論値 2x = 6）
```

数値微分の方法: 中心差分（Richardson 補外付き）。

### 積分

**例: ∫ x² dx, x: 0→1**

```
[1] f(x): x^2
[2] a: 0
[3] b: 1
[4] Enter
→ 0.3333333（1/3）
```

数値積分の方法: 適応型 Simpson 法。

### 総和（Sum）

**例: Σ i², i: 1→10**

```
[1] f(i): i^2
[2] a: 1
[3] b: 10
[4] Enter
→ 385
```

**確認**: 1²+2²+...+10² = 385

### 総乗（Product）

**例: Π i, i: 1→5（5!）**

```
[1] f(i): i
[2] a: 1
[3] b: 5
[4] Enter
→ 120
```

