## 6.2 複素数

### 複素数とは

**複素数** は、実数と虚数を組み合わせた数です。

```
z = a + bi
```

- `a`: 実部
- `b`: 虚部
- `i`: 虚数単位（i² = -1）

中学・高校では扱いませんが、大学の電気工学・量子力学などで登場します。

### 複素数メニュー（Fn + 7）

```
┌─────────────────────────────────┐
│▌Complex                         │
├─────────────────────────────────┤
│1 z = a+bi                       │
│2 z + w                          │
│3 z - w                          │
│4 z * w                          │
│5 z / w                          │
│6 |z|, arg z, conj z             │
│7 z polar form                   │
│8 z^n                            │
│9 z^(1/n)                        │
│10 exp/sin/cos/log               │
│11 Back                          │
└─────────────────────────────────┘
```

### 例: z = 3 + 4i の絶対値

```
[1] Fn + 7 → 6 (|z|, arg, conj)
[2] Re(z): 3
[3] Im(z): 4
→ |z| = 5, arg = 53.13°, conj = 3-4i
```

**計算内容**:
- |z| = √(3² + 4²) = √25 = 5
- arg = atan2(4, 3) = 53.13°（DEG モード）
- conj = 3 - 4i

### 例: 2 つの複素数の積

```
z = 1 + 2i
w = 3 + 4i
z * w = ?

[1] Fn + 7 → 4 (z * w)
[2] z の Re, Im を入力
[3] w の Re, Im を入力
→ 結果 = -5 + 10i
```

**計算内容**:
(1+2i)(3+4i) = 3 + 4i + 6i + 8i² = 3 + 10i - 8 = -5 + 10i

### 例: 極形式

複素数を「絶対値 r」と「偏角 θ」で表す形式。

```
z = 3 + 4i
極形式: 5 ∠ 53.13°
```

`Fn + 7 → 7 (z polar form)` で確認できます。

### 例: 累乗

ド・モアブルの定理により、極形式で計算されます。

```
z = 3 + 4i
z^2 = ?
→ 5² ∠ (2 × 53.13°) = 25 ∠ 106.26° = -7 + 24i
```

